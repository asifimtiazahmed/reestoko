          'isPurchased': false,
          'isAutoGenerated': true,
          'addedBy': 'usr_alex_123',
        },
      ];

      for (final shop in shopItems1) {
        final shopRef = house1Ref.collection('shopping_list').doc(shop['id'] as String);
        shop['createdAt'] = FieldValue.serverTimestamp();
        batch.set(shopRef, shop);
      }

      // Commit Batch Write
      await batch.commit();
      AppLogger.i('Cloud Firestore demo seeding complete!');
