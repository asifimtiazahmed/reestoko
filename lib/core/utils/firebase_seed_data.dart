/// **Architecture Layer**: Core / Utils
/// **Purpose**: Programmatic Firestore Data Seeder for populating demo families, users, storage zones, and groceries.

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:reestoko/core/utils/app_logger.dart';

class FirebaseSeedData {
  static final FirebaseFirestore _firestore = FirebaseFirestore.instance;

  /// Seed demo households, storage zones, and items into Cloud Firestore
  static Future<void> seedDemoData() async {
    AppLogger.i('Starting Cloud Firestore demo data seeding...');

    try {
      final batch = _firestore.batch();

      // =======================================================================
      // 1. Household 1: Johnson Family Pantry
      // =======================================================================
      final house1Ref = _firestore.collection('households').doc('house_johnson_01');
      batch.set(house1Ref, {
        'id': 'house_johnson_01',
        'name': 'Johnson Family Pantry',
        'ownerUid': 'usr_alex_123',
        'memberUids': ['usr_alex_123'],
        'createdAt': FieldValue.serverTimestamp(),
      });

      // Zones for Household 1
      final zones1 = [
        {'id': 'zone_fridge', 'name': 'Fridge', 'iconName': 'snowflake', 'itemCount': 6},
        {'id': 'zone_pantry', 'name': 'Pantry', 'iconName': 'archive', 'itemCount': 5},
        {'id': 'zone_freezer', 'name': 'Freezer', 'iconName': 'cube', 'itemCount': 3},
      ];

      for (final zone in zones1) {
        final zoneRef = house1Ref.collection('zones').doc(zone['id'] as String);
        batch.set(zoneRef, zone);
      }

      // Grocery Items for Household 1
      final items1 = [
        {
          'id': 'item_101',
