          'barcode': '012345678905',
          'createdBy': 'usr_alex_123',
        },
        {
          'id': 'item_102',
          'name': 'Whole Wheat Loaf',
          'zoneId': 'zone_pantry',
          'category': 'Bakery',
          'quantity': 1,
          'minThreshold': 1,
          'unit': 'loaf',
          'status': 'NORMAL',
          'expirationDate': DateTime.now().add(const Duration(days: 5)).toIso8601String(),
          'barcode': '012345678906',
          'createdBy': 'usr_alex_123',
        },
        {
          'id': 'item_103',
          'name': 'Large Grade A Eggs 12ct',
          'zoneId': 'zone_fridge',
          'category': 'Dairy',
          'quantity': 1,
          'minThreshold': 1,
          'unit': 'pack',
          'status': 'LOW_STOCK',
          'expirationDate': DateTime.now().add(const Duration(days: 8)).toIso8601String(),
          'barcode': '012345678907',
          'createdBy': 'usr_alex_123',
        },
        {
          'id': 'item_104',
          'name': 'Red Bell Peppers',
          'zoneId': 'zone_fridge',
          'category': 'Produce',
