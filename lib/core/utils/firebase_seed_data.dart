          'expirationDate': DateTime.now().add(const Duration(days: 6)).toIso8601String(),
          'createdBy': 'usr_alex_123',
        },
        {
          'id': 'item_105',
          'name': 'Boneless Chicken Breast',
          'zoneId': 'zone_freezer',
          'category': 'Meat',
          'quantity': 2,
          'minThreshold': 1,
          'unit': 'kg',
          'status': 'NORMAL',
          'expirationDate': DateTime.now().add(const Duration(days: 60)).toIso8601String(),
          'createdBy': 'usr_alex_123',
        },
      ];

      for (final item in items1) {
        final itemRef = house1Ref.collection('items').doc(item['id'] as String);
        item['createdAt'] = FieldValue.serverTimestamp();
        item['updatedAt'] = FieldValue.serverTimestamp();
        batch.set(itemRef, item);
      }

      // Shopping List for Household 1
      final shopItems1 = [
        {
          'id': 'shop_101',
          'name': 'Greek Yogurt 500g',
          'quantityToBuy': 2,
